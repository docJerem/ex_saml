defmodule ExSaml.RouterUtil do
  @moduledoc false

  alias Plug.Conn
  require Logger
  alias ExSaml.{Core, Helper, IdpData}

  @subdomain_re ~r/^(?<subdomain>([^.]+))?\./

  def check_idp_id(conn, _opts) do
    idp_id_from = Application.get_env(:ex_saml, :idp_id_from)

    idp_id =
      if idp_id_from == :subdomain do
        case Regex.named_captures(@subdomain_re, conn.host) do
          %{"subdomain" => idp_id} -> idp_id
          _ -> nil
        end
      else
        case conn.params do
          %{"idp_id_seg" => [idp_id]} ->
            idp_id

          %{"idp_id" => idp_id} ->
            idp_id

          _ ->
            nil
        end
      end

    idp = idp_id && Helper.get_idp(idp_id)

    if idp do
      conn |> Conn.put_private(:ex_saml_idp, idp)
    else
      conn |> Conn.send_resp(403, "invalid_request unknown IdP") |> Conn.halt()
    end
  end

  @doc """
  Reads the `target_url` parameter, the URL the browser is sent to after the
  SAML exchange, into `conn.private[:ex_saml_target_url]`.

  The value must be a relative path, or one of the IdP's `allowed_target_urls`
  when the IdP is known (`conn.private[:ex_saml_idp]`); anything else answers
  400. The authorization code is appended to it, so it must not point
  anywhere the application does not control.
  """
  def check_target_url(conn, _opts) do
    case conn.params["target_url"] do
      nil ->
        Conn.put_private(conn, :ex_saml_target_url, nil)

      raw ->
        target_url = URI.decode_www_form(raw)

        if target_url_allowed?(target_url, conn.private[:ex_saml_idp]) do
          Conn.put_private(conn, :ex_saml_target_url, target_url)
        else
          Logger.error(
            "[ExSaml] target_url must be a relative path or one of allowed_target_urls: " <>
              inspect(target_url)
          )

          conn |> Conn.send_resp(400, "invalid target_url") |> Conn.halt()
        end
    end
  rescue
    ArgumentError ->
      Logger.error(
        "[ExSaml] target_url must be x-www-form-urlencoded: #{inspect(conn.params["target_url"])}"
      )

      conn |> Conn.send_resp(400, "target_url must be x-www-form-urlencoded") |> Conn.halt()
  end

  @doc false
  def target_url_allowed?(url, idp) when is_binary(url) do
    relative_path?(url) or
      (match?(%IdpData{allowed_target_urls: [_ | _]}, idp) and url in idp.allowed_target_urls)
  end

  def target_url_allowed?(_url, _idp), do: false

  @doc """
  Whether `url` is a path on this host: a single leading `/`, no scheme or
  authority, and nothing a browser could read as one (backslashes, control
  characters).
  """
  @spec relative_path?(String.t()) :: boolean()
  def relative_path?(url) when is_binary(url) do
    String.starts_with?(url, "/") and not String.starts_with?(url, "//") and
      not String.contains?(url, "\\") and not String.match?(url, ~r/[\x00-\x1F\x7F]/) and
      match?(%URI{scheme: nil, host: nil}, URI.parse(url))
  end

  def relative_path?(_), do: false

  # generate URIs using the idp_id
  @spec ensure_sp_uris_set(Core.SpConfig.t(), Conn.t()) :: Core.SpConfig.t()
  def ensure_sp_uris_set(%Core.SpConfig{metadata_uri: metadata_uri} = sp, conn) do
    case metadata_uri do
      [?/ | _] ->
        base_url = build_base_url(conn)
        idp_id_from = Application.get_env(:ex_saml, :idp_id_from)

        path_segment_idp_id =
          if idp_id_from == :subdomain do
            nil
          else
            %IdpData{id: idp_id} = conn.private[:ex_saml_idp]
            idp_id
          end

        %{
          sp
          | metadata_uri: Helper.get_metadata_uri(base_url, path_segment_idp_id),
            consume_uri: Helper.get_consume_uri(base_url, path_segment_idp_id),
            logout_uri: Helper.get_logout_uri(base_url, path_segment_idp_id)
        }

      _ ->
        sp
    end
  end

  @doc """
  Send a SAML Request.

  remove_saml_encoding flag is curently used only by Lemon LDAP SSOs, we think Lemon has a bug.
  The SAMLEncoding params in the query is returned as invalid by Lemon.
  As it's the default value that is used anyway we simply delete it when Lemon is the Provider.

  use_redirect? flag is used to define if the request should be HTTP Redirect or HTTP POST.
  Most of the time HTTP POST is used and prefered.

  ## Examples

      iex> send_saml_request(%Conn{}, "https://...", false, '<xml>...', "...", true)
      %Conn{}

  """
  # resp_body is generated by Core.Binding.encode_http_post/4 (standard SAML POST binding form), not user input.
  # sobelow_skip ["XSS.SendResp"]
  def send_saml_request(
        conn,
        idp_url,
        use_redirect?,
        signed_xml_payload,
        relay_state,
        remove_saml_encoding? \\ false
      ) do
    if use_redirect? do
      standard_url =
        Core.Binding.encode_http_redirect(idp_url, signed_xml_payload, nil, relay_state)

      # SAML Encoding query param is currentlty not accepted by LemonLDAP (bug? and perhaps other IDP(s) ?)
      maybe_url_without_saml_encoding =
        if remove_saml_encoding?, do: remove_saml_encoding(standard_url), else: standard_url

      redirect(conn, 302, maybe_url_without_saml_encoding)
    else
      nonce = conn.private[:ex_saml_nonce]
      resp_body = Core.Binding.encode_http_post(idp_url, signed_xml_payload, relay_state, nonce)

      conn
      |> Conn.put_resp_header("content-type", "text/html")
      |> Conn.send_resp(200, resp_body)
    end
  end

  def redirect(conn, status_code, dest) do
    conn
    |> Conn.put_resp_header("location", dest)
    |> Conn.send_resp(status_code, "")
    |> Conn.halt()
  end

  defp build_base_url(conn) do
    scheme = Atom.to_string(conn.scheme)
    host = conn.host
    port = conn.port

    port_str =
      case {scheme, port} do
        {"http", 80} -> ""
        {"https", 443} -> ""
        {_, p} when is_integer(p) -> ":#{p}"
        _ -> ""
      end

    "#{scheme}://#{host}#{port_str}/sso"
  end

  defp remove_saml_encoding(url) do
    encoded_param = URI.encode_query(%{"SAMLEncoding" => IdpData.oasis_redirect_flow_uri()})

    String.replace(url, encoded_param <> "&", "")
  end
end
